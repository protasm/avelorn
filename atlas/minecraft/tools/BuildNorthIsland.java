import java.awt.Point;
import java.io.*;
import java.nio.file.*;
import java.util.*;
import org.pepsoft.worldpainter.*;
import org.pepsoft.worldpainter.layers.*;
import org.pepsoft.worldpainter.layers.exporters.ResourcesExporter.ResourcesExporterSettings;
import org.pepsoft.worldpainter.exporting.*;
import org.pepsoft.worldpainter.plugins.WPPluginManager;
import org.pepsoft.minecraft.SeededGenerator;
import org.pepsoft.util.*;

/** Reproducible Minecraft derivative; all writes go to the supplied output folder.
 * Uses WorldPainter 2.27.1's native tile, world-save and Java export APIs.
 * A source square always retains its 4x4 footprint. Bilinear interpolation only
 * affects dry surface heights; water bodies retain their explicitly prepared beds.
 */
public final class BuildNorthIsland {
    private static final long SEED = 20260906L;
    private static final String NAME = "Avelorn - North Island (4x)";
    private static final int MIN = -64, MAX = 320;
    private static int width, height;
    private static float[] surface, water;
    private static byte[] codes;

    /** Read the documented big-endian array interchange generated by Python. */
    private static int[] load(Path folder) throws IOException {
        try (DataInputStream in = new DataInputStream(new BufferedInputStream(Files.newInputStream(folder.resolve("north-island.bin"))))) {
            width = in.readInt(); height = in.readInt();
            int sx = in.readInt(), sz = in.readInt();
            in.readInt(); in.readInt();
            int n = width * height;
            surface = new float[n]; water = new float[n]; codes = new byte[n];
            for (int i=0;i<n;i++) surface[i]=in.readFloat();
            for (int i=0;i<n;i++) water[i]=in.readFloat();
            in.readFully(codes);
            if (in.read()!=-1) throw new IOException("Trailing input data");
            return new int[]{sx,sz};
        }
    }

    /** Smooth dry terrain within the source sampling grid, preserving the mask. */
    private static float terrainHeight(int x, int z, int index) {
        int code = codes[index] & 255;
        if (code <= 3) return surface[index];
        double fx = (x - 1.5)/4.0, fz = (z - 1.5)/4.0;
        int ix = (int)Math.floor(fx), iz = (int)Math.floor(fz);
        double dx = fx-ix, dz = fz-iz, value=0, weight=0;
        for(int j=0;j<2;j++) for(int i=0;i<2;i++) {
            int cx=Math.max(0,Math.min(width-1,ix+i));
            int cz=Math.max(0,Math.min(height-1,iz+j));
            int k=cz*width+cx;
            if ((codes[k]&255)<=3) continue;
            double a=(i==0?1-dx:dx)*(j==0?1-dz:dz);
            value+=surface[k]*a; weight+=a;
        }
        return Math.max(63,(float)(weight>0?value/weight:surface[index]));
    }

    private static Terrain material(String id, int code) {
        if(code==0 || code==1 || code==2 || code==3) return Terrain.GRAVEL;
        if(code==8 || code==57) return Terrain.SAND;
        if(code==50) return Terrain.SNOW;
        if(code==35 || code==51) return Terrain.GRAVEL;
        if(code==36 || code==44 || code==9 || code==41 || code==52) return Terrain.STONE;
        if(code==39 || code==58) return Terrain.BASALT;
        if(id.contains("wetland")) return Terrain.MUD;
        return Terrain.GRASS;
    }

    public static void main(String[] args) throws Exception {
        Path out=Paths.get(args[0]).toAbsolutePath();
        Configuration config=new Configuration();
        Configuration.setInstance(config);
        config.setMaxThreadCount(3);
        config.setPingAllowed(false);
        WPPluginManager.initialise(config.getUuid(), null);
        World2 world;
        Path worldPath=out.resolve("North Island 4x.world");
        if(args.length>1 && args[1].equals("export")) {
            WorldIO io=new WorldIO();
            try(InputStream in=Files.newInputStream(worldPath)){io.load(in);}
            world=io.getWorld();
        } else {
            int[] spawn=load(out);
            List<String> ids=Files.readAllLines(out.resolve("terrain-ids.txt"));
            Platform platform=DefaultPlugin.JAVA_ANVIL_26_1;
            System.out.println("Platform: "+platform.displayName);
            TileFactory factory=TileFactoryFactory.createFlatTileFactory(SEED,Terrain.GRASS,MIN,MAX,40,62,false,false);
            world=new World2(platform,SEED,factory);
            world.setName(NAME);
            world.setGameType(GameType.CREATIVE);
            world.setAllowCheats(true);
            world.setDifficulty(0);
            world.setMapFeatures(false);
            world.setSpawnPoint(new Point(spawn[0],spawn[1]));
            Dimension dim=world.getDimension(Dimension.Anchor.NORMAL_DETAIL);
            dim.setGenerator(new SeededGenerator(Generator.DEFAULT,SEED));
            dim.setPopulate(false);
            dim.setSubsurfaceMaterial(Terrain.STONE);
            dim.setTopLayerMinDepth(3);
            dim.setTopLayerVariation(0);
            dim.setLayerSettings(Resources.INSTANCE,ResourcesExporterSettings.defaultSettings(platform,Dimension.Anchor.NORMAL_DETAIL,MIN,MAX));
            Terrain[] materials=new Terrain[64];
            Layer[] trees=new Layer[64];
            int[] treeDensity=new int[64];
            for(int c=0;c<64;c++) {
                String id=ids.get(c); materials[c]=material(id,c);
                if(id.contains("forest") || id.contains("wood")) {
                    trees[c]=(c>=27 && c<=29)?PineForest.INSTANCE:DeciduousForest.INSTANCE;
                    treeDensity[c]=id.contains("wood")?3:6;
                }
            }
            int tw=width*4/128, th=height*4/128;
            for(int tz=0;tz<th;tz++) {
                for(int tx=0;tx<tw;tx++) {
                    Tile tile=new Tile(tx,tz,MIN,MAX);
                    tile.inhibitEvents();
                    for(int z=0;z<128;z++) for(int x=0;x<128;x++) {
                        int wx=tx*128+x,wz=tz*128+z;
                        int k=(wz/4)*width+(wx/4),c=codes[k]&255;
                        tile.setHeight(x,z,terrainHeight(wx,wz,k));
                        tile.setWaterLevel(x,z,Math.round(water[k]));
                        tile.setTerrain(x,z,materials[c]);
                        // Explicit water biomes prevent inland water appearing oceanic.
                        if(c==0) tile.setLayerValue(Biome.INSTANCE,x,z,0);
                        else if(c<=3) tile.setLayerValue(Biome.INSTANCE,x,z,7);
                        if(trees[c]!=null) tile.setLayerValue(trees[c],x,z,treeDensity[c]);
                        if(c==50) tile.setBitLayerValue(Frost.INSTANCE,x,z,true);
                    }
                    tile.releaseEvents();
                    dim.addTile(tile);
                }
                if(tz%5==0) System.out.println("Terrain rows: "+(tz+1)+"/"+th);
            }
            if(dim.getTileCount()!=tw*th) throw new IllegalStateException("Incomplete tile coverage");
            if(dim.getIntHeightAt(spawn[0],spawn[1])<dim.getWaterLevelAt(spawn[0],spawn[1])) throw new IllegalStateException("Spawn under water");
            System.out.println("Tiles: "+dim.getTileCount()+"; spawn surface: "+dim.getHeightAt(spawn[0],spawn[1]));
            try(OutputStream stream=Files.newOutputStream(worldPath)){new WorldIO(world).save(stream);}
            System.out.println("Saved editable world: "+worldPath);
            surface=null;water=null;codes=null;System.gc();
        }
        Path saves=out.resolve("saves"); Files.createDirectories(saves);
        if(Files.exists(saves.resolve(NAME))) throw new IOException("Export destination exists; preserve or remove it explicitly before retrying");
        new JavaWorldExporter(world,WorldExportSettings.EXPORT_EVERYTHING).export(saves.toFile(),NAME,null,new ProgressReceiver(){
            private int last=-1;
            public synchronized void setProgress(float p){int pc=(int)(p*100);if(pc>last){last=pc;System.out.println("Export "+pc+"%");}}
            public void setMessage(String m){System.out.println(m);}
            public void exceptionThrown(Throwable t){t.printStackTrace();}
            public void done(){System.out.println("Export stage finished");}
            public void checkForCancellation(){}
            public void reset(){}
            public void subProgressStarted(SubProgressReceiver p){}
        });
        System.out.println("EXPORT COMPLETE "+saves.resolve(NAME));
    }
}
